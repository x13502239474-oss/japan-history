这次政变在法律上极为重要。它不只是罢免了庆喜，还规定了新政府的构成原则：不是大名会议，而是「有司」主导的官僚政府。这一点常被忽视，却决定了此后二十年的政治格局——明治政府从一开始就不是代议制的，它是政变产生的政府，因此它的合法性必须靠「天皇的亲裁」和「富强的成绩」来补足。

