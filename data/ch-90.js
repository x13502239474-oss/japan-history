二十一世纪的日本社会，发生了几个深层的变化。

**「格差社会」与「下流社会」。** 非正规雇用的扩大、收入差距的增加，使「一亿总中流」的自我形象瓦解。「下流社会」（三浦展）描述了一个「不贫穷但无希望」的阶层。

