这个意识的基础是真实的：高速增长使实际工资持续上升（一九六〇至一九七〇年间，实际工资增长约一倍）；失业率低（约百分之一）；收入差距相对较小（基尼系数约零点三）；社会保障（健康保险、年金）逐步完善。

