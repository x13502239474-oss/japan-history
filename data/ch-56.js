山县有朋是日本近代军队的缔造者，也是「军部政治」的发明者。他两次组阁（一八八九、一八九八），长期担任枢密院议长，通过人事任命控制陆军。他留下的不只是制度，还有一种政治文化：军队应当在国家政治中扮演「超然」的、指导性的角色。

山县于一九二二年去世后，陆军失去了能够统合各派的权威，派系斗争公开化。此后的陆军大致分为两派。

**长州派**（以山县的继承者为主）：主张渐进扩张、与政党合作、重视对苏备战。代表人物有田中义一、宇垣一成。

**萨摩派**（海军为主）：主张对美备战、海军优先。

