教育改革的目标，是废除战时的军国主义教育，建立民主的教育体系。

**教育基本法（一九四七年三月）。** 规定教育的目的是「培养作为和平国家与社会的建设者、热爱真理与正义、尊重个人价值、重视勤劳与责任、充满独立精神的身心健康的国民」。它废除了教育敕语，确立了「教育机会均等」「义务教育」「男女同校」等原则。

**学校教育法（一九四七年三月）。** 建立「六三三四」学制：小学六年、初中三年（义务教育）、高中三年、大学四年。这一学制取代了战前的「六五三」制（小学六年、中学五年、高等学校三年、大学三年），使教育更加普及与平等。

