第三，它分裂了曾经的倒幕同盟。西乡、大久保、木户在战争中合作无间，但战后对「如何对待士族」「如何对待朝鲜」产生分歧，最终导致一八七三年的明治六年政变，西乡下野，进而有一八七七年的西南战争。

第四，它留下了「朝敌」这个政治标签。会津在战后长期被视为「贼军」，其士族在明治初期遭受系统性排斥。这种地方性的创伤记忆，直到二十世纪后期仍在福岛的地方叙事中存在。
