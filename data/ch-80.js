一九六〇年代的日本，经历了一场消费革命。

**「三种神器」：** 黑白电视、洗衣机、冰箱。一九六〇年前后，这些家电开始普及；一九六四年东京奥运会后，彩电、空调、汽车（「新三种神器」）成为新的目标。

